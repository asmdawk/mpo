import { _electron as electron } from '@playwright/test';
import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs/promises';

const root=path.resolve(import.meta.dirname,'..');
const data=path.join(root,'tests/native-profile');
await fs.rm(data,{recursive:true,force:true});
const errors=[];
const env={...process.env,XDG_CACHE_HOME:'/workspace/work/cache',XDG_CONFIG_HOME:'/workspace/work/config'};
const options={args:['--no-sandbox','--ozone-platform=headless','--disable-gpu',`--user-data-dir=${data}`,process.env.ZIGZAK_TEST_APP || root],env,timeout:30000};
let instance;
try {
  instance=await electron.launch(options);
  const page=await instance.firstWindow();
  page.on('pageerror',e=>errors.push(e.message));
  await page.waitForSelector('.track-row');
  await page.waitForFunction(()=>document.querySelector('#duration').textContent==='0:24');
  assert.equal(await page.locator('.track-row').count(),1);
  const initial=await page.evaluate(()=>window.zigzak.getInitialState());
  assert.equal(initial.demo.id,'zigzak-demo');
  assert.match(initial.demo.url,/^zigzak-media:/);
  const range=await page.evaluate(async url=>{const response=await fetch(url,{headers:{Range:'bytes=100-199'}});return {status:response.status,range:response.headers.get('content-range'),bytes:(await response.arrayBuffer()).byteLength};},initial.demo.url);
  assert.equal(range.status,206);assert.equal(range.bytes,100);assert.match(range.range,/^bytes 100-199\//);
  console.log('PASS native preload, metadata and ranged media protocol');
  await page.locator('#play-button').click();
  await page.waitForFunction(()=>document.querySelector('#media').currentTime>0.4);
  await page.locator('#play-button').click();
  assert.equal(await page.locator('#media').evaluate(m=>m.paused),true);
  console.log('PASS native WebAudio demo playback and pause');
  await instance.evaluate(({dialog}, files)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:files});},[path.join(root,'tests/fixtures/sample.mp3'),path.join(root,'tests/fixtures/sample.mp4')]);
  await page.locator('.add-button').click();
  await page.waitForFunction(()=>document.querySelectorAll('.track-row').length===3);
  const mp3=page.locator('.track-row').filter({hasText:'Тестовый трек'});
  assert.equal(await mp3.count(),1);
  await mp3.click();
  await page.waitForFunction(()=>document.querySelector('#media').currentTime>0.2 && document.querySelector('#media').duration<5);
  await mp3.locator('.track-favorite').click();
  console.log('PASS native MP3 playback and Cyrillic ID3');
  const video=page.locator('.track-row').filter({hasText:'MP4'});
  await video.click();
  await page.waitForFunction(()=>document.querySelector('#media').videoWidth===480 && document.querySelector('#media').currentTime>0.2);
  assert.equal(await page.locator('#app').evaluate(a=>a.classList.contains('is-video')),true);
  await page.locator('#seek').fill('600');
  await page.locator('#seek').dispatchEvent('input');
  await page.waitForFunction(()=>document.querySelector('#media').currentTime>2);
  await page.locator('#play-button').click();
  console.log('PASS native H264/AAC MP4 decode and range seeking');
  await page.locator('.video-expand').click();
  await page.waitForFunction(()=>document.fullscreenElement?.id==='video-stage');
  await page.keyboard.press('Escape');
  await page.evaluate(async()=>{if(document.fullscreenElement)await document.exitFullscreen();});
  console.log('PASS native video fullscreen permission');
  await page.locator('.eq-shortcut').click();
  await page.locator('#eq-enabled').check();
  await page.locator('#eq-preset').selectOption('bass');
  await page.locator('#speed').selectOption('1.5');
  assert.equal(await page.locator('#media').evaluate(m=>m.playbackRate),1.5);
  assert.equal(await page.locator('#eq-bands input[type=range]').count(),10);
  await page.locator('[data-action=close-eq]').click();
  await page.locator('#volume').fill('48');await page.locator('#volume').dispatchEvent('input');
  for(const theme of ['sunset','aurora','violet']) {
    await page.locator(`[data-action=theme][data-theme=${theme}]`).click();
    assert.equal(await page.locator('html').getAttribute('data-theme'),theme);
    assert.equal(await page.locator(`[data-action=theme][data-theme=${theme}]`).getAttribute('aria-pressed'),'true');
  }
  const exportPath=path.join(root,'tests/exported.m3u8');
  await instance.evaluate(({dialog},filePath)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath});},exportPath);
  await page.locator('[data-action=export-playlist]').click();
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('сохран'));
  const exported=await fs.readFile(exportPath,'utf8');assert.match(exported,/#EXTM3U/);assert.match(exported,/sample.mp3/);
  console.log('PASS native EQ/rate/volume and UTF8 playlist export');
  await page.locator('[data-action=view-library]').click();
  await page.screenshot({path:path.join(root,'tests/native-video.png')});
  await page.locator('.track-row').filter({hasText:'Neon Skyline'}).click();
  await page.waitForFunction(()=>document.querySelector('#media').currentTime>0.4 && document.querySelector('#media').duration===24);
  await page.locator('#play-button').click();
  await page.screenshot({path:path.join(root,'tests/native-preview.png')});
  await page.locator('[data-action=close]').click();
  await instance.process().once('exit',()=>{});
  await new Promise(resolve=>{if(instance.process().exitCode!==null)resolve();else instance.process().once('exit',resolve);});
  const saved=JSON.parse(await fs.readFile(path.join(data,'library.json'),'utf8'));
  assert.equal(saved.tracks.length,3);assert.equal(saved.settings.volume,48);assert.equal(saved.settings.rate,1.5);assert.equal(saved.settings.eqPreset,'bass');assert.equal(saved.settings.theme,'violet');
  assert.equal(saved.tracks.find(t=>t.path.endsWith('sample.mp3')).favorite,true);
  assert(saved.tracks.some(t=>t.lastPlayedAt>0));assert.equal(saved.settings.lastTrackId,'zigzak-demo');
  instance=await electron.launch(options);
  const restored=await instance.firstWindow();await restored.waitForFunction(()=>document.querySelectorAll('.track-row').length===3);
  const restoredState=await restored.evaluate(()=>window.zigzak.getInitialState());
  assert.equal(restoredState.settings.volume,48);assert.equal(restoredState.tracks.filter(t=>t.favorite).length,1);
  assert.equal(restoredState.settings.theme,'violet');assert.equal(await restored.locator('html').getAttribute('data-theme'),'violet');
  await restored.locator('[data-action=view-recent]').click();
  assert.equal(await restored.locator('.track-row').count(),3);
  assert.deepEqual(errors,[]);
  console.log('PASS native close handshake and restart persistence (queue, favorites, recent, EQ, volume, rate)');
  console.log('Native Electron integration: all checks passed.');
} finally { if(instance)await instance.close().catch(()=>{}); }
